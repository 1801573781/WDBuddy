/** 单页（已裁净）精确提取：背景沿用原图像素，只产出可编辑文字槽 */
export function buildPanelSpecPrompt(): string {
  return `你是资深 PPT 版式分析器。下面这张图是**一页幻灯片**的完整截图（已裁净，不含其它页）。请精确输出该页的**文字槽位**，用于生成"背景像素 100% 还原 + 文字可编辑"的 PPT 模板。

只输出 JSON（不要解释、不要 markdown 围栏）：
{
  "kind": "cover|toc|section|content|content-3col|content-4col|timeline|two-col|list|closing",
  "vibe": "一句话风格（30 字内）",
  "tone": {"bg": "#0e1e3c", "text": "#ffffff", "accent": "#35d6ff"},
  "slots": [
    {
      "type": "text",
      "role": "title|subtitle|item-title|item-body|body|number|decor|footer",
      "text": "占位文字",
      "x": 12.5, "y": 8.0, "w": 60.0, "h": 10.0,
      "size": 40, "color": "#ffffff", "bold": true, "align": "center",
      "bg": "#0e1e3c"
    }
  ]
}

【硬性规则】
1. x/y/w/h 为 0-100 归一化（相对本页宽高），x/y 是**文本框左上角**，必须按原图文字的**实际包围盒**给出（误差 ≤1）。w 要足以容纳占位文字（宁宽勿窄，避免成品折行）。
2. size 为磅值：页高 7.5in = 100 单位，故 1 单位 ≈ 0.075in ≈ 5.4pt；字号 ≈ 原图文字高度(单位) × 3.9。参考：封面主标题 36-54、页面标题 24-30、条目标题 16-20、正文 11-14、编号 18-28、英文装饰 10-14。
3. bg 必填：该文字**紧邻背景的平均色**（用于盖住原图文字，渐变/星空背景取平均色）。取不到就填 tone.bg。
4. role 必须准确：title=页面主标题；subtitle=副标题；item-title=卡片/条目标题；item-body=条目说明；number=编号数字（01/02…）；decor=纯装饰英文（CONTENTS/PART ONE/THANKS）；footer=页脚落款。
5. text 一律示例化：主标题写"在此输入主标题文字内容"；页面标题写"在此输入标题内容"；条目标题写"添加标题一/二/三"；条目说明写"在这里输入说明文字"；编号照原样写"01"；装饰英文照原样写。**保留原图的分行数与字符量级**（原图 8 字标题 → 占位 8-10 字），并沿用原图的对齐方式。
6. **只列文字，不要列装饰图形**（星球/光带/图标/插图/照片/色块/线条一律不写，它们已经由背景像素承载）。除非该图形内含文字（如圆环里的编号），此时按文字槽给出。
7. 逐字核对原图，禁止臆造不存在的文字。`;
}

