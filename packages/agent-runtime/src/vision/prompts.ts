/**
 * 视觉提取提示词（对齐 WDClaude 级联方案）
 *
 * 为什么内联为 TS 常量而不是 .txt 资源：
 * tsc 只编译源码、不拷贝静态资源，dist 运行时读 prompts/*.txt 必然 ENOENT。
 * 常量随编译产物一起分发，零部署负担。
 *
 * 级联方案要点（与 WDClaude 一致）：
 * - 视觉模型只做"看图转述"，输出结构化分区（文字内容/布局/细节/不确定区域/差异），
 *   由主模型在文本上下文里做推理，避免主模型直接吃像素带来的不稳定
 * - 不确定区域用归一化坐标标注，配合 view_image 二次特写形成"两阶段协议"
 * - 纯图模式追加意图画像，避免用户只丢一张图时主模型猜错目标
 */

