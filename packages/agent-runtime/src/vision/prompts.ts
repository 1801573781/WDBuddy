/** 语义 region → 归一化外接框（视觉模型定位，配合裁剪特写） */
export function buildLocatorPrompt(description: string): string {
  return `你是图像区域定位器。给定一张图像与一段区域描述，请找到该区域，输出覆盖它（含描述中的外扩要求，如"周围 200px"）的归一化外接框。

要求：
- 坐标为归一化值，范围 [0,1]，原点在左上角，x 向右、y 向下
- box 必须完整包住目标；描述含"周围 Npx"类外扩时按比例并入 box
- 只输出 JSON，不要任何其他文字，格式：
{"label": "<区域的一句话命名>", "box": {"x0": 0.0, "y0": 0.0, "x1": 1.0, "y1": 1.0}}

区域描述：${description}`;
}

